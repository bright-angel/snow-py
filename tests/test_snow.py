"""Tests for the snow package.

These tests serve two purposes:

1. Exercise fresh encode -> extract round trips across the compression and
   encryption option matrix.
2. Decode the committed ``testa/b/c.txt`` fixtures and recover the expected
   messages.

Note on the fixtures: the ``testa/b/c.txt`` files shipped in the original
repository were produced by the upstream *C* ``snow`` tool and are *not*
decodable by this Python port. They have been regenerated with this project's
own encoder (``snow -C -p 123456 -m "flag{aaa}" ...`` etc.) so they act as a
stable regression anchor: if the package ever drifts from the original
behaviour, these tests catch it. The fixtures are marked ``binary`` in
``.gitattributes`` so git's line-ending translation cannot corrupt the
whitespace-encoded payload.
"""

from __future__ import annotations

import io
import os

import snow
from snow import cli, config, encrypt
from snow.core import message_extract, message_string_encode, space_calculate

DATA_DIR = os.path.join(os.path.dirname(__file__), "data")


def _reset(compress: bool, password) -> None:
    """Put the package into a known state before an encode/decode operation."""
    config.compress_flag = compress
    config.quiet_flag = True  # keep stderr quiet during tests
    config.line_length = 80
    if password is None:
        encrypt._ice_key = None
    else:
        encrypt.password_set(password)


def _encode(cover: str, msg: str, compress: bool = False, password=None) -> str:
    _reset(compress, password)
    inf = io.StringIO(cover)
    outf = io.StringIO()
    assert message_string_encode(msg, inf, outf)
    return outf.getvalue()


def _decode(stego: str, compress: bool = False, password=None) -> bytes:
    _reset(compress, password)
    inf = io.StringIO(stego)
    outf = io.BytesIO()
    assert message_extract(inf, outf)
    return outf.getvalue()


def _cover(n: int = 40, text: str = "cover line with some text content\n") -> str:
    return text * n


def test_roundtrip_plain():
    msg = "flag{secret_message}"
    stego = _encode(_cover(), msg)
    assert _decode(stego) == msg.encode()


def test_roundtrip_compressed():
    msg = "the quick brown fox jumps over the lazy dog 1234567890"
    stego = _encode(_cover(), msg, compress=True)
    assert _decode(stego, compress=True) == msg.encode()


def test_roundtrip_encrypted():
    msg = "topsecret"
    stego = _encode(_cover(), msg, password="hunter2")
    assert _decode(stego, password="hunter2") == msg.encode()


def test_roundtrip_compressed_encrypted():
    msg = "combo test message with compression and encryption layers"
    stego = _encode(_cover(60), msg, compress=True, password="p@ssw0rd")
    assert _decode(stego, compress=True, password="p@ssw0rd") == msg.encode()


def test_decode_fixture_testa():
    # Regenerated by: snow -C -p 123456 -m "flag{aaa}" tests/data/test.txt
    with open(os.path.join(DATA_DIR, "testa.txt"), "r", encoding="utf-8", newline="") as f:
        stego = f.read()
    assert _decode(stego, compress=True, password="123456") == b"flag{aaa}"


def test_decode_fixture_testb():
    # Regenerated by: snow -C -m "flag{bbb}" tests/data/test.txt
    with open(os.path.join(DATA_DIR, "testb.txt"), "r", encoding="utf-8", newline="") as f:
        stego = f.read()
    assert _decode(stego, compress=True) == b"flag{bbb}"


def test_decode_fixture_testc():
    # Regenerated by: snow -m "flag{ccc}" tests/data/test.txt
    with open(os.path.join(DATA_DIR, "testc.txt"), "r", encoding="utf-8", newline="") as f:
        stego = f.read()
    assert _decode(stego) == b"flag{ccc}"


def test_space_calculate_runs(capsys):
    _reset(False, None)
    inf = io.StringIO(_cover())
    space_calculate(inf)
    captured = capsys.readouterr()
    assert "storage capacity" in captured.out


def test_cli_version(capsys):
    assert cli.main(["--version"]) == 0
    assert "Apache-2.0" in capsys.readouterr().out
